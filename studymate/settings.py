# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases


def _mysql_password():
    password = os.environ.get('DJANGO_DB_PASSWORD')
    if password or os.name != 'nt':
        return password or ''

    import winreg

    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, 'Environment') as key:
            return winreg.QueryValueEx(key, 'DJANGO_DB_PASSWORD')[0]
    except (FileNotFoundError, OSError):
        return ''


database_engine = os.environ.get('DJANGO_DB_ENGINE', 'mysql').lower()
use_sqlite = database_engine in {'sqlite', 'sqlite3'}

if use_sqlite:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    try:
        import pymysql
        pymysql.install_as_MySQLdb()
    except ImportError as exc:
        raise RuntimeError(
            'PyMySQL is required for the MySQL backend. Install it with "pip install pymysql".'
        ) from exc

    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': os.environ.get('DJANGO_DB_NAME', 'studymate'),
            'USER': os.environ.get('DJANGO_DB_USER', 'studymate_user'),
            'PASSWORD': _mysql_password(),
            'HOST': os.environ.get('DJANGO_DB_HOST', '127.0.0.1'),
            'PORT': os.environ.get('DJANGO_DB_PORT', '3307'),
            'OPTIONS': {
                'charset': 'utf8mb4',
            },
        }
    }


